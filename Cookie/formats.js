// Format codec layer: parse + serialize cookies across multiple formats.

export const FORMATS = ['json', 'netscape', 'setcookie', 'header', 'base64'];

/* ---------- detection ---------- */

export function detectFormat(text) {
  const t = (text || '').trim();
  if (!t) return 'header';
  if (t.startsWith('{') || t.startsWith('[')) return 'json';

  // base64 → JSON
  if (/^[A-Za-z0-9+/=\r\n]+$/.test(t)) {
    const dec = tryB64(t);
    if (dec && (dec.trim().startsWith('{') || dec.trim().startsWith('['))) return 'base64';
  }

  const lines = t.split(/\r?\n/).filter((l) => l.trim());
  if (/netscape/i.test(t)) return 'netscape';
  if (lines.some((l) => l.split('\t').length >= 7)) return 'netscape';
  if (lines.some((l) => /^\s*set-cookie:/i.test(l))) return 'setcookie';
  if (lines.some((l) => /;\s*(domain|path|expires|max-age|samesite|secure|httponly)\s*=/i.test(l)))
    return 'setcookie';
  return 'header';
}

/* ---------- parse ---------- */

export function parse(text, fmt = detectFormat(text)) {
  switch (fmt) {
    case 'json': return fromJSON(text);
    case 'base64': return fromJSON(tryB64(text) || '[]');
    case 'netscape': return fromNetscape(text);
    case 'setcookie': return fromSetCookie(text);
    default: return fromHeader(text);
  }
}

function fromJSON(text) {
  const data = JSON.parse(text);
  return Array.isArray(data) ? data : data.cookies || [];
}

function fromNetscape(text) {
  const out = [];
  for (const raw of text.split(/\r?\n/)) {
    if (!raw || raw.startsWith('#')) continue;
    const p = raw.split('\t');
    if (p.length < 7) continue;
    const [domain, flag, path, secure, expires, name, value] = p;
    out.push({
      domain,
      path: path || '/',
      secure: secure.toUpperCase() === 'TRUE',
      httpOnly: false,
      hostOnly: flag.toUpperCase() !== 'TRUE',
      expirationDate: Number(expires) > 0 ? Number(expires) : undefined,
      session: !(Number(expires) > 0),
      name,
      value
    });
  }
  return out;
}

function fromSetCookie(text) {
  const out = [];
  for (let line of text.split(/\r?\n/)) {
    line = line.trim().replace(/^set-cookie:\s*/i, '');
    if (!line || !line.includes('=')) continue;
    const parts = line.split(';');
    const [name, ...vrest] = parts[0].split('=');
    const cookie = { name: name.trim(), value: vrest.join('=').trim(), path: '/' };
    for (const attr of parts.slice(1)) {
      const [k, ...v] = attr.split('=');
      const key = k.trim().toLowerCase();
      const val = v.join('=').trim();
      if (key === 'domain') cookie.domain = val;
      else if (key === 'path') cookie.path = val;
      else if (key === 'secure') cookie.secure = true;
      else if (key === 'httponly') cookie.httpOnly = true;
      else if (key === 'samesite') cookie.sameSite = val.toLowerCase().replace('-', '_');
      else if (key === 'max-age') cookie.expirationDate = Math.floor(Date.now() / 1000) + Number(val);
      else if (key === 'expires') {
        const ts = Date.parse(val);
        if (!isNaN(ts)) cookie.expirationDate = Math.floor(ts / 1000);
      }
    }
    out.push(cookie);
  }
  return out;
}

function fromHeader(text) {
  const out = [];
  const body = text.replace(/^cookie:\s*/i, '');
  for (const pair of body.split(';')) {
    const i = pair.indexOf('=');
    if (i < 0) continue;
    const name = pair.slice(0, i).trim();
    if (!name) continue;
    out.push({ name, value: pair.slice(i + 1).trim(), path: '/' });
  }
  return out;
}

/* ---------- serialize ---------- */

export function serialize(fmt, cookies, meta = {}) {
  switch (fmt) {
    case 'json': return toJSON(cookies, meta);
    case 'base64': return toB64(toJSON(cookies, meta));
    case 'netscape': return toNetscape(cookies);
    case 'setcookie': return toSetCookie(cookies);
    default: return toHeader(cookies);
  }
}

const toJSON = (cookies, meta) =>
  JSON.stringify({ ...meta, cookies }, null, 2);

function toNetscape(cookies) {
  const head = '# Netscape HTTP Cookie File\n# Generated by Cookie Snap\n';
  return head + cookies.map((c) => [
    c.domain,
    c.domain.startsWith('.') ? 'TRUE' : 'FALSE',
    c.path || '/',
    c.secure ? 'TRUE' : 'FALSE',
    c.session ? 0 : Math.floor(c.expirationDate || 0),
    c.name,
    c.value
  ].join('\t')).join('\n') + '\n';
}

function toSetCookie(cookies) {
  return cookies.map((c) => {
    let s = `${c.name}=${c.value}`;
    if (c.domain) s += `; Domain=${c.domain}`;
    if (c.path) s += `; Path=${c.path}`;
    if (c.expirationDate) s += `; Expires=${new Date(c.expirationDate * 1000).toUTCString()}`;
    if (c.secure) s += '; Secure';
    if (c.httpOnly) s += '; HttpOnly';
    if (c.sameSite && c.sameSite !== 'unspecified')
      s += `; SameSite=${c.sameSite.replace('_', '-').replace(/\b\w/g, (m) => m.toUpperCase())}`;
    return s;
  }).join('\n');
}

const toHeader = (cookies) => cookies.map((c) => `${c.name}=${c.value}`).join('; ');

const toB64 = (s) => btoa(unescape(encodeURIComponent(s)));
function tryB64(s) {
  try { return decodeURIComponent(escape(atob(s.replace(/\s+/g, '')))); }
  catch { return null; }
}